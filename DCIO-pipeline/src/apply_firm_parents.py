"""(2026-10-27) Fill manager_parent_name on the three holdings tables for the given ack_ids.

Runs the same MERGEs the 5500statemachine runs unscoped (0q3a/b/c in
s3://retirementinsights-reference/sqls/, generated by core-data-platform
athena/sql/firm_acquisitions/gen_parent_sql.py), scoped to this run's acks.
The filed manager is never changed. Only approved default.firm_acquisitions rows apply.
The step is idempotent, so a rerun only touches rows whose parent changed.

    python3.11 -m src.apply_firm_parents --ack-ids A,B        # or --ack-file f / --all
"""
import argparse
import os
import sys

import awswrangler as wr
import boto3

DB = "default"
WORKGROUP = os.environ.get("ATHENA_WORKGROUP", "primary")
S3_OUTPUT = os.environ.get("ATHENA_RESULTS", "s3://retirementinsights-silver/athena-results/")
SQL_BUCKET = "retirementinsights-reference"
SQL_KEYS = ["sqls/0q3a_firm_parent_alt.sql", "sqls/0q3b_firm_parent_mf.sql", "sqls/0q3c_firm_parent_cit.sql"]
SCOPE_T = "1=1 /*SCOPE_T*/"
SCOPE_H = "1=1 /*SCOPE_H*/"
ACK_CHUNK = 300


def log(msg):
    print(f"[apply_firm_parents] {msg}", flush=True)


def load_acks(args):
    if args.all:
        return None
    acks = []
    if args.ack_ids:
        acks += args.ack_ids.split(",")
    if args.ack_file:
        acks += open(args.ack_file).read().split()
    acks = sorted({a.strip() for a in acks if a.strip()})
    if not acks:
        sys.exit("No ack_ids given (use --ack-ids, --ack-file or --all)")
    return acks


def scoped(sql, chunk):
    if chunk is None:
        return sql
    assert sql.count(SCOPE_T) == 1 and sql.count(SCOPE_H) == 1, "scope tokens missing from S3 SQL"
    ids = ",".join("'" + a.replace("'", "''") + "'" for a in chunk)
    return sql.replace(SCOPE_T, f"t.ack_id IN ({ids})").replace(SCOPE_H, f"h.ack_id IN ({ids})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ack-ids", help="comma-separated ack_ids")
    ap.add_argument("--ack-file", help="file with whitespace-separated ack_ids")
    ap.add_argument("--all", action="store_true", help="whole tables (same as the state machine)")
    args = ap.parse_args()
    acks = load_acks(args)
    chunks = [None] if acks is None else [acks[i:i + ACK_CHUNK] for i in range(0, len(acks), ACK_CHUNK)]
    log(f"scope: {'ALL acks' if acks is None else f'{len(acks)} ack_ids'}")
    s3 = boto3.client("s3")
    for key in SQL_KEYS:
        sql = s3.get_object(Bucket=SQL_BUCKET, Key=key)["Body"].read().decode("utf-8")
        for ch in chunks:
            qid = wr.athena.start_query_execution(sql=scoped(sql, ch), database=DB, workgroup=WORKGROUP,
                                                  s3_output=S3_OUTPUT, wait=False)
            res = wr.athena.wait_query(query_execution_id=qid)
            n = res.get("Statistics", {}).get("DataManipulationQuery", {}).get("RowsUpdated") if isinstance(res, dict) else None
            log(f"ok {key.split('/')[-1]} qid={qid}" + (f" rows={n}" if n is not None else ""))
    log("done")


if __name__ == "__main__":
    main()
